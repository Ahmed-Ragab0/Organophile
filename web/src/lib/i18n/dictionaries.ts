/**
 * Widens the literal string types produced by `as const` back to `string`,
 * while preserving the key structure. That is what makes the English
 * dictionary type-check: a missing or misspelled KEY is still a build error,
 * but the VALUE is free to be different text.
 */
type Widen<T> = T extends string ? string : { [K in keyof T]: Widen<T[K]> };

export type Dict = Widen<typeof ar>;

